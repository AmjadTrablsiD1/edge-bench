#!/usr/bin/env bash
# Install Edge Bench (macOS) out of the repo and build every way of starting it.
#
# Idempotent -- safe to run after every change, and *required* after one: the
# shortcuts run the installed copy in ~/.local/share, not this repo.
# Windows: use scripts/make_windows_package.sh and copy the zip instead.
set -euo pipefail

APP_ID="edge-bench"
APP_NAME="Edge Bench"
APP_ICON="⏱"

SRC="$(cd "$(dirname "$0")" && pwd)"
DEST="$HOME/.local/share/$APP_ID"
STATE="$HOME/.local/state/$APP_ID"
SHORTCUTS="$HOME/Desktop/Apps"
BASE_PYTHON="${BASE_PYTHON:-/opt/miniconda3/bin/python3}"

mkdir -p "$DEST" "$STATE/logs" "$SHORTCUTS" "$HOME/.config/$APP_ID"

echo "==> Building the UI"
( cd "$SRC/ui" && npm install --silent && npm run build )

echo "==> Copying the app to $DEST"
rsync -a --delete \
  --exclude '.git' --exclude '.venv' --exclude 'node_modules' --exclude '/dist' \
  --exclude 'ui/node_modules' --exclude '__pycache__' --exclude '.pytest_cache' \
  --exclude 'tests' --exclude 'test-results' --exclude 'playwright-report' \
  --exclude 'ui/src' --exclude 'ui/public' \
  "$SRC/" "$DEST/"

echo "==> Python environment"
PY="$DEST/.venv/bin/python3"
[ -x "$PY" ] || "$BASE_PYTHON" -m venv "$DEST/.venv"
"$DEST/.venv/bin/pip" install -q -r "$DEST/requirements.txt"

echo "==> Shortcut: $SHORTCUTS/$APP_NAME.command"
# .command runs in Terminal, which already holds the Desktop/Documents
# permissions an unsigned .app is silently denied -- and captures live there.
CMD="$SHORTCUTS/$APP_NAME.command"
cat > "$CMD" <<LAUNCH
#!/usr/bin/env bash
# Generated by install.sh -- edit the repo, not this file.
cd "$DEST"
exec "$PY" "$DEST/main.py" "\$@"
LAUNCH
chmod +x "$CMD"

echo "==> App Launcher tile"
python3 "$DEST/scripts/register_launcher.py" \
  --id "$APP_ID" --name "$APP_NAME" --icon "$APP_ICON" --category "Apps" \
  --description "Saleae edge timing: reference edge to every channel, out to Excel" \
  --cwd "$DEST" --command "\"$PY\" \"$DEST/main.py\"" --bundle

echo "==> Icon (after the tile: mkapp writes an emoji icon that this replaces)"
bash "$SRC/scripts/make_icon.sh" "$SRC/branding/icon.svg" "$APP_NAME" "$SRC/ui/public" >/dev/null

echo
echo "$APP_NAME is installed."
echo "  Double-click : $CMD"
echo "  or the $APP_ICON $APP_NAME tile in App Launcher"
echo "  Logs         : $STATE/logs"
